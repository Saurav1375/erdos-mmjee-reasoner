"""Final report v4b = the Phase-4 report + a post-hoc "Phase 4b" section (V4B_PREREG.md).

Reads Phase-4b artifacts only (artifacts_v4b/: analysis/v4b.json,
verifier_v4b/answer_level/report.json) and writes report/final_v4b/: metrics_v4b.json,
generated/macros_v4b.tex, generated/t_v4b_*.tex and figures/v4b_decomp.pdf. The v3 and Phase-4
generated tables, macros and figures are copied unchanged from report/final_v4/, which is never
written, so every earlier section of the report stays identical.

usage: .venv/bin/python scripts/final_report_v4b.py && cd report/final_v4b && tectonic final_report_v4b.tex
"""

from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

from final_report_v3 import dtex, tex_escape  # noqa: E402

A4B = ROOT / "artifacts_v4b"
V4 = ROOT / "report" / "final_v4"
OUT = ROOT / "report" / "final_v4b"
FIG, GEN = OUT / "figures", OUT / "generated"
YEARS = {"2025": "TwentyFive", "2026": "TwentySix"}


def collect() -> dict:
    return {"analysis": json.loads((A4B / "analysis" / "v4b.json").read_text()),
            "answer_level": json.loads((A4B / "verifier_v4b" / "answer_level" / "report.json")
                                       .read_text())}


def macros(m: dict) -> dict[str, str]:
    an, al = m["analysis"], m["answer_level"]
    d = {}
    for y, k in YEARS.items():
        dec, disc = an["decomposition"][y], an["discrimination"][y]
        d[f"VbPool{k}"] = dtex(dec["pool_gain"])
        d[f"VbSel{k}"] = dtex(dec["selection_gain"])
        d[f"VbAucAll{k}"] = f"{disc['auc_all_candidates']:.2f}"
        d[f"VbAucIn{k}"] = f"{disc['within_pool']['mean']:.2f}"
    ch = al["configs"][al["chosen"]]
    d["VbAChosen"] = tex_escape(al["chosen"])
    d["VbARows"] = f"{al['rows_answers']:,}".replace(",", "{,}")
    d["VbACands"] = f"{al['rows_candidates']:,}".replace(",", "{,}")
    d["VbAMean"] = f"{ch['v3_16pool']['mean']:.1f}"
    d["VbAWorst"] = f"{ch['v3_16pool']['worst_year']:.1f}"
    d["VbARef"] = f"{al['v3_ref']['mean']:.1f}"
    d["VbARefWorst"] = f"{al['v3_ref']['worst_year']:.1f}"
    d["VbAMaj"] = f"{al['majority']['v3_16pool']:.1f}"
    b, img = an["dev_b"]["all"], an["dev_b"]["diagram_questions"]
    d["VbBMaj"] = dtex(b["majority8"]["diff"])
    d["VbBSample"] = dtex(b["per_sample_s4_s7"]["diff"])
    d["VbBImgCur"] = f"{img['per_sample_s4_s7']['current']:.1f}"
    d["VbBImgDiag"] = f"{img['per_sample_s4_s7']['diagram']:.1f}"
    d["VbBOrcRef"] = f"{b['oracle8']['reference']:.1f}"
    d["VbBOrcMulti"] = f"{b['oracle8']['multi_view']:.1f}"
    d["VbBTrCur"] = f"{b['truncated_s4_s7']['current']:.1f}"
    d["VbBTrDiag"] = f"{b['truncated_s4_s7']['diagram']:.1f}"
    return d


def tex_table(path: str, caption: str, label: str, cols: str, head: list[str],
              body: list[list[str]]) -> None:
    lines = [r"\begin{table}[!t]", r"\centering", r"\scriptsize", rf"\caption{{{caption}}}",
             rf"\label{{{label}}}", r"\setlength{\tabcolsep}{2.5pt}", rf"\begin{{tabular}}{{{cols}}}",
             r"\toprule", " & ".join(head) + r" \\", r"\midrule"]
    lines += [r"\midrule" if r == ["MID"] else " & ".join(r) + r" \\" for r in body]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (GEN / path).write_text("\n".join(lines) + "\n")


def write_tex(m: dict) -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "macros_v4b.tex").write_text(
        "% generated by scripts/final_report_v4b.py - do not edit\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros(m).items()))
    an = m["analysis"]
    dec, disc = an["decomposition"], an["discrimination"]
    f1 = lambda v: f"{v:.1f}"  # noqa: E731
    rows = [["Matched self-consistency"] + [f1(dec[y]["matched_sc"]) for y in YEARS],
            ["Majority vote on the v3 pool"] + [f1(dec[y]["majority_v3_pool"]) for y in YEARS],
            ["v3 pick (verifier v3)"] + [f1(dec[y]["v3_pick"]) for y in YEARS],
            ["MID"],
            ["Pool gain"] + [dtex(dec[y]["pool_gain"]) for y in YEARS],
            ["\\textbf{Selection gain}"] + [dtex(dec[y]["selection_gain"]) for y in YEARS],
            ["Total gain"] + [dtex(dec[y]["total_gain"]) for y in YEARS],
            ["MID"],
            ["Candidate AUC, all"] + [f"{disc[y]['auc_all_candidates']:.3f}" for y in YEARS],
            ["Candidate AUC, mixed pools"]
            + [f"{disc[y]['within_pool']['mean']:.3f} ({disc[y]['within_pool']['n_mixed_pools']})"
               for y in YEARS]]
    tex_table("t_v4b_decomp.tex",
              "Where the v3 gain over matched self-consistency comes from (\\%; differences in "
              "points, 95\\% cluster-bootstrap CI). Pool gain: majority vote on the v3 pool "
              "$-$ matched SC; selection gain: v3 pick $-$ majority on the same pool. Frozen v3 "
              "verifier and existing pools only. Mixed pools hold both right and wrong answers "
              "(number of pools in brackets).",
              "tab:v4bdecomp", "lrr", ["", "2025", "2026"], rows)
    blocks = ("all", "diagram_questions", "text_questions")
    b = {k: an["dev_b"][k] for k in blocks}
    pair = lambda k, a, c: f"{b[k][a][c[0]]:.1f} / {b[k][a][c[1]]:.1f}"  # noqa: E731
    ref = ("reference", "multi_view")
    cur = ("current", "diagram")
    rows = [["Majority@8"] + [pair(k, "majority8", ref) for k in blocks],
            ["\\textbf{Diff.\\ (gate)}"] + [dtex(b[k]["majority8"]["diff"]) for k in blocks],
            ["Oracle@8"] + [pair(k, "oracle8", ref) for k in blocks],
            ["Distinct answers"]
            + [f"{b[k]['distinct_answers']['reference']:.2f} / "
               f"{b[k]['distinct_answers']['multi_view']:.2f}" for k in blocks],
            ["MID"],
            ["Per sample"] + [pair(k, "per_sample_s4_s7", cur) for k in blocks],
            ["Diff."] + [dtex(b[k]["per_sample_s4_s7"]["diff"]) for k in blocks],
            ["Truncated"] + [pair(k, "truncated_s4_s7", cur) for k in blocks],
            ["Tokens (k)"]
            + [f"{b[k]['tokens_s4_s7']['current'] / 1000:.1f} / "
               f"{b[k]['tokens_s4_s7']['diagram'] / 1000:.1f}" for k in blocks]]
    tex_table("t_v4b_diag.tex",
              "Diagram-first transcript on the 2024 dev year (\\%; differences in points, 95\\% "
              "cluster-bootstrap CI). Existing: PoT with the v3 transcript, samples 0--7; mixed: "
              "samples 0--3 of it plus samples 4--7 solved from the diagram-first transcript "
              "with the same seeds; top cells: existing / mixed. Bottom: samples 4--7 only, cells: "
              "current / diagram-first reading. Gate (fixed in advance): majority@8 difference $>0$ with lower bound $>0$.",
              "tab:v4bdiag", "lrrr",
              ["", f"All ({b['all']['n']})", f"Diagram ({b['diagram_questions']['n']})",
               f"Text ({b['text_questions']['n']})"], rows)


def figure(m: dict) -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    dec = m["analysis"]["decomposition"]
    steps = [("matched_sc", "Matched SC", "#bbbbbb"),
             ("majority_v3_pool", "Majority, v3 pool", "#4c72b0"),
             ("v3_pick", "v3 pick", "#dd8452")]
    fig, ax = plt.subplots(figsize=(3.4, 2.2))
    for i, (key, label, color) in enumerate(steps):
        xs = [j + (i - 1) * 0.26 for j in range(len(YEARS))]
        vals = [dec[y][key] for y in YEARS]
        ax.bar(xs, vals, 0.26, label=label, color=color)
        for x, v in zip(xs, vals):
            ax.text(x, v + 0.5, f"{v:.1f}", ha="center", fontsize=6)
    ax.set_xticks(range(len(YEARS)), list(YEARS), fontsize=7)
    ax.set_ylim(45, 78)
    ax.set_ylabel("Accuracy (%)", fontsize=7)
    ax.tick_params(axis="y", labelsize=7)
    ax.legend(fontsize=6, loc="upper right", ncol=1, frameon=False)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(FIG / f"v4b_decomp.{ext}", dpi=200)
    plt.close(fig)


def copy_v4() -> None:
    for sub in ("generated", "figures"):
        (OUT / sub).mkdir(parents=True, exist_ok=True)
        for f in (V4 / sub).iterdir():
            shutil.copy2(f, OUT / sub / f.name)


def main() -> None:
    copy_v4()
    m = collect()
    (OUT / "metrics_v4b.json").write_text(json.dumps(m, indent=2, default=float))
    write_tex(m)
    figure(m)
    print(f"wrote {OUT / 'metrics_v4b.json'}, {GEN}/, {FIG}/")


if __name__ == "__main__":
    main()
