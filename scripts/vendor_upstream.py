def extract_functions(nb_path: Path, cell: int, names: list[str]) -> dict[str, str]:
    """Return {name: exact source text (with class indentation)} for methods in a cell."""
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    src = "".join(nb["cells"][cell]["source"])
    tree = ast.parse(src)
    found: dict[str, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name in names:
            found[node.name] = ast.get_source_segment(src, node, padded=True)
    missing = set(names) - set(found)
    if missing:
        raise RuntimeError(f"{nb_path}: functions not found: {missing}")
    return found


def main() -> None:
    here = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo", type=Path, default=here / "third_party" / "mmJEE-Eval")
    parser.add_argument(
        "--out", type=Path, default=here / "src/mmjee_reasoner/scoring/upstream.py"
    )
    args = parser.parse_args()

    provenance = ""
    body = ""
    for rel, cell, cls, names in SOURCES:
        funcs = extract_functions(args.repo / rel, cell, names)
        provenance += f"* ``{rel}`` cell {cell}: {', '.join(names)}\n"
        body += f"\nclass {cls}:\n"
        body += f'    """Shim holding verbatim methods from ``{rel}`` (cell {cell})."""\n\n'
        for name in names:
            body += funcs[name] + "\n\n"
    args.out.write_text(HEADER.format(provenance=provenance) + body, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
