"""Regenerate ``src/mmjee_reasoner/scoring/upstream.py`` from the mmJEE-Eval notebooks.

The base paper ships its answer-extraction and scoring code only inside Jupyter
notebooks, as methods of evaluator classes. The SOP requires that we reuse these
functions *without changes*, so this script copies their source text
byte-for-byte (located with ``ast``) into thin shim classes. Run it once; the
test ``tests/test_scoring.py`` re-checks that the vendored text is still
identical to the notebooks.

Usage:
    python scripts/vendor_upstream.py [--repo third_party/mmJEE-Eval]
"""

